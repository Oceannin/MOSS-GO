export const LANGUAGE_KEY = "moss-go.language.v1";
export function initialLanguage(storage) {
  try {
    return (storage ?? globalThis.localStorage)?.getItem(LANGUAGE_KEY) === "ru"
      ? "ru"
      : "en";
  } catch {
    return "en";
  }
}
let language = initialLanguage();
export function currentLanguage() {
  return language;
}
export function t(key) {
  return (language === "ru" ? RU : EN)[key] ?? EN[key] ?? key;
}
export function setLanguage(next) {
  language = next === "ru" ? "ru" : "en";
  try {
    localStorage.setItem(LANGUAGE_KEY, language);
  } catch {}
  applyTranslations();
}
export function applyTranslations(root = document) {
  document.documentElement.lang = language;
  for (const item of root.querySelectorAll("[data-i18n]"))
    item.textContent = t(item.dataset.i18n);
  for (const attribute of ["aria-label", "title", "alt"])
    for (const item of root.querySelectorAll(`[data-i18n-${attribute}]`))
      item.setAttribute(
        attribute,
        t(item.getAttribute(`data-i18n-${attribute}`)),
      );
  const button = document.querySelector("#language");
  if (button) button.textContent = language.toUpperCase();
}
